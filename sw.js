// Service worker Doudizhu Kung2. Diisi scripts/build.mjs: versi (hash isi file) dan daftar precache.
//
// Strategi (sama dengan Mahjong Kung2): jaringan dulu, cache sebagai cadangan. Selama online pemain selalu dapat versi terbaru
// (tidak ada risiko HTML baru + JS lama), dan kalau offline game tetap bisa dibuka untuk main sendiri.
// Semua yang di bawah api/ tidak pernah dicache.
const VERSION = '__VERSION__'; // diganti saat build
const CACHE = `ddz-${VERSION}`;
const PRECACHE = __PRECACHE__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((c) => c.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('ddz-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || url.pathname.includes('/api/')) return;

  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(async () => {
        const hit = await caches.match(req, { ignoreSearch: true });
        if (hit) return hit;
        if (req.mode === 'navigate') return (await caches.match('./index.html')) || Response.error();
        return Response.error();
      }),
  );
});
